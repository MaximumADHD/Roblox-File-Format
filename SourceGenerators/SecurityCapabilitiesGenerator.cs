using System.Globalization;
using System.Text;

namespace RobloxFiles.SourceGenerators
{
    [Generator]
    public sealed class SecurityCapabilitiesGenerator : IIncrementalGenerator
    {
        private static readonly DiagnosticDescriptor InvalidBitIndex = new DiagnosticDescriptor(
            "RFFSG001",
            "Security capability does not fit in a ulong",
            "Security capability '{0}' has bit index {1}; expected a value from 0 to 63",
            "RobloxFileFormat",
            DiagnosticSeverity.Error,
            isEnabledByDefault: true);

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var capabilities = context.SyntaxProvider.CreateSyntaxProvider(
                (node, cancellationToken) => node is EnumDeclarationSyntax declaration
                    && declaration.Identifier.ValueText == "SecurityCapability",
                (syntaxContext, cancellationToken) => syntaxContext.SemanticModel.GetDeclaredSymbol(
                    (EnumDeclarationSyntax)syntaxContext.Node, cancellationToken) as INamedTypeSymbol)
                .Where(symbol => symbol != null
                    && symbol.ToDisplayString() == "RobloxFiles.Enums.SecurityCapability");

            context.RegisterSourceOutput(capabilities, Generate);
        }

        private static void Generate(SourceProductionContext context, INamedTypeSymbol capability)
        {
            var source = new StringBuilder();
            source.AppendLine("// <auto-generated/>");
            source.AppendLine("namespace RobloxFiles");
            source.AppendLine("{");
            source.AppendLine("    [global::System.Flags]");
            source.AppendLine("    public enum SecurityCapabilities : ulong");
            source.AppendLine("    {");

            foreach (var member in capability.GetMembers().OfType<IFieldSymbol>())
            {
                if (!member.HasConstantValue)
                    continue;

                decimal bitIndex = Convert.ToDecimal(member.ConstantValue, CultureInfo.InvariantCulture);

                if (bitIndex < 0 || bitIndex > 63)
                {
                    context.ReportDiagnostic(Diagnostic.Create(
                        InvalidBitIndex,
                        member.Locations.FirstOrDefault(),
                        member.Name,
                        bitIndex.ToString(CultureInfo.InvariantCulture)));
                    continue;
                }

                foreach (var attribute in member.GetAttributes())
                {
                    if (attribute.AttributeClass?.ToDisplayString() == "System.ObsoleteAttribute")
                        source.Append("        [global::").Append(attribute.ToString()).AppendLine("]");
                }

                source.Append("        @").Append(member.Name).Append(" = 1UL << ")
                    .Append(bitIndex.ToString(CultureInfo.InvariantCulture)).AppendLine(",");
            }

            source.AppendLine("    }");
            source.AppendLine("}");

            context.AddSource("SecurityCapabilities.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        }
    }
}